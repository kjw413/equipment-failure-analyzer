"""Write deterministic formula caches without requiring Excel on the report PC.

All formulas are generated by this package; expected values come from the same
validated analysis snapshot. Excel still recalculates formulas on opening.
This is NOT a general formula evaluator.
"""
from __future__ import annotations
import math, os, posixpath, tempfile
from pathlib import Path
from zipfile import ZipFile,ZIP_DEFLATED
from xml.etree import ElementTree as ET

NS='http://schemas.openxmlformats.org/spreadsheetml/2006/main'
REL='http://schemas.openxmlformats.org/officeDocument/2006/relationships'
PKG='http://schemas.openxmlformats.org/package/2006/relationships'

class FormulaCache:
    def __init__(self):self.values={}

    def set(self,ws,cell: str,formula: str,expected):
        if not formula.startswith('='):raise ValueError('Formula must start with =')
        if isinstance(expected,float) and not math.isfinite(expected):expected=''
        if expected is None:expected=''
        ws[cell]=formula
        self.values[(ws.title,cell)]=expected
        return ws[cell]

    def patch(self,path: Path):
        fd,tmp=tempfile.mkstemp(suffix='.xlsx',dir=path.parent);os.close(fd)
        try:
            with ZipFile(path,'r') as src, ZipFile(tmp,'w',ZIP_DEFLATED) as dst:
                rels=ET.fromstring(src.read('xl/_rels/workbook.xml.rels'))
                targets={r.attrib['Id']:r.attrib['Target'] for r in rels}
                book=ET.fromstring(src.read('xl/workbook.xml'))
                sheet_paths={}
                for sheet in book.find(f'{{{NS}}}sheets'):
                    target=targets[sheet.attrib[f'{{{REL}}}id']]
                    full=target.lstrip('/') if target.startswith('/') else posixpath.normpath('xl/'+target)
                    sheet_paths[full]=sheet.attrib['name']
                for info in src.infolist():
                    data=src.read(info.filename)
                    if info.filename in sheet_paths:
                        root=ET.fromstring(data);name=sheet_paths[info.filename]
                        for cell in root.iter(f'{{{NS}}}c'):
                            key=(name,cell.attrib.get('r'))
                            if key not in self.values:continue
                            v=cell.find(f'{{{NS}}}v')
                            if v is None:v=ET.SubElement(cell,f'{{{NS}}}v')
                            value=self.values[key]
                            if isinstance(value,str):cell.set('t','str');v.text=value
                            elif isinstance(value,bool):cell.set('t','b');v.text='1' if value else '0'
                            else:
                                cell.pop('t',None) if hasattr(cell,'pop') else cell.attrib.pop('t',None)
                                v.text=format(float(value),'.15g')
                        data=ET.tostring(root,encoding='utf-8',xml_declaration=True)
                    dst.writestr(info,data)
            os.replace(tmp,path)
        finally:
            Path(tmp).unlink(missing_ok=True)
